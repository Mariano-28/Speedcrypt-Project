    /// - Speedcrypt.exe may be intentionally excluded during development builds.
    ///
    /// Security scope and limits:
    /// - This mechanism detects unauthorized binary modification at runtime.
    /// - It is effective against accidental corruption and basic tampering.
    /// - It does not claim resistance against a fully privileged attacker.
    /// - No software-only anti-tamper solution is ever absolute or unbeatable.
    ///
    /// Operational behavior:
    /// - On integrity violation, control is delegated to AntiTamperProtection.
    /// - Optional secure wiping can be triggered depending on configuration.
    /// - Validation may involve sensitive material (master key, password buffers).
